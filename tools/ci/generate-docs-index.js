#!/usr/bin/env node
'use strict';
/**
 * generate-docs-index.js (v9.0.368)
 * Generates docs/INDEX.md — a grouped table of contents of every docs/*.md,
 * with the first heading of each file as its title, plus an "archivable"
 * section for docs that are old AND unreferenced anywhere in the repo.
 *
 * Usage: node tools/ci/generate-docs-index.js
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');
const DOCS = path.join(ROOT, 'docs');

const GROUPS = [
  { name: '🔋 Battery', rx: /battery/i },
  { name: '🔘 Buttons & flows', rx: /button|flow/i },
  { name: '📡 Zigbee / pairing / IAS', rx: /zigbee|ias|pairing|cluster|dp_mapping/i },
  { name: '🌍 Forum & community', rx: /forum|community/i },
  { name: '🐙 GitHub', rx: /github/i },
  { name: '🤖 AI / automation', rx: /\bai\b|auto|antigravity|orchestr/i },
  { name: '📱 Devices & drivers', rx: /device|driver|brand|fingerprint/i },
  { name: '🏗️ Architecture & rules', rx: /architect|rule|best_practice|best-practice|athom|policy|sacred|contributing|branching|checklist/i },
  { name: '📊 Reports & audits', rx: /report|audit|analysis|investigation|synthesis|matrix/i },
  { name: '📋 P-series (fix journals)', rx: /^p\d+/i },
];

function firstHeading(file) {
  try {
    for (const line of fs.readFileSync(file, 'utf8').split('\n').slice(0, 30)) {
      const m = line.match(/^#\s+(.+)/);
      if (m) {return m[1].trim().slice(0, 120);}
    }
  } catch { /* unreadable */ }
  return null;
}

function lastModified(rel) {
  try {
    return execSync(`git log -1 --format=%cs -- "${rel}"`, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch { return null; }
}

function referencedElsewhere(name) {
  try {
    const out = execSync(
      `git grep -l -F "${name}" -- . ":!docs/${name}" ":!.github/state" ":!docs/INDEX.md" || true`,
      { cwd: ROOT, encoding: 'utf8' }).trim();
    return out.length > 0;
  } catch { return true; } // en cas de doute: considérer référencé (ne pas archiver)
}

function main() {
  const files = fs.readdirSync(DOCS).filter(f => f.endsWith('.md') && f !== 'INDEX.md').sort();
  const grouped = new Map(GROUPS.map(g => [g.name, []]));
  const other = [];
  const archivable = [];

  for (const f of files) {
    const rel = `docs/${f}`;
    const title = firstHeading(path.join(DOCS, f)) || f;
    const date = lastModified(rel);
    const entry = { f, title, date };
    const g = GROUPS.find(g => g.rx.test(f));
    (g ? grouped.get(g.name) : other).push(entry);
    // archivable: pas référencé et > 60 jours
    if (date && (Date.now() - new Date(date).getTime()) > 60 * 86400000 && !referencedElsewhere(f)) {
      archivable.push(entry);
    }
  }

  const L = [];
  L.push('# 📚 Documentation Index', '');
  L.push('> Auto-generated by `tools/ci/generate-docs-index.js` — do not edit by hand.', '');
  L.push(`${files.length} documents. Hubs: [Forum hub](./FORUM_HUB.md) · [GitHub hub](./GITHUB_HUB.md)`, '');
  for (const [name, entries] of grouped) {
    if (!entries.length) {continue;}
    L.push(`## ${name} (${entries.length})`, '');
    for (const e of entries) {L.push(`- [${e.title}](./${e.f})${e.date ? ` — _${e.date}_` : ''}`);}
    L.push('');
  }
  if (other.length) {
    L.push(`## 📄 Divers (${other.length})`, '');
    for (const e of other) {L.push(`- [${e.title}](./${e.f})${e.date ? ` — _${e.date}_` : ''}`);}
    L.push('');
  }
  L.push('## 🗄️ Candidats à l\'archivage (non référencés, > 60 jours)', '');
  if (archivable.length) {
    for (const e of archivable) {L.push(`- [${e.f}](./${e.f}) — _${e.date}_`);}
  } else {
    L.push('- Aucun');
  }
  L.push('');

  fs.writeFileSync(path.join(DOCS, 'INDEX.md'), L.join('\n'));
  console.log(`[docs-index] ${files.length} docs indexés, ${archivable.length} candidats archivage`);
}

main();
