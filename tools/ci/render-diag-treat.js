#!/usr/bin/env node
'use strict';

/**
 * render-diag-treat.js — Build human-readable TREAT.md from diagnostics-report.json
 *
 * Usage:
 *   node tools/ci/render-diag-treat.js
 *   node tools/ci/render-diag-treat.js --out=reports/gmail-forum-2026-08-23
 */

const fs = require('fs');
const path = require('path');
const { renderTreatTableRows, enrich } = require('../../lib/diagnostics/DiagContentEnricher');

const ROOT = path.resolve(__dirname, '..', '..');
const REPORT = path.join(ROOT, '.github', 'state', 'diagnostics-report.json');
const outArg = process.argv.find((a) => a.startsWith('--out='));
const OUT_DIR = outArg
  ? path.resolve(ROOT, outArg.split('=')[1])
  : path.join(ROOT, 'reports', `gmail-forum-${new Date().toISOString().slice(0, 10)}`);

function main() {
  if (!fs.existsSync(REPORT)) {
    console.error('[render-diag-treat] Missing', REPORT);
    process.exit(1);
  }
  const report = JSON.parse(fs.readFileSync(REPORT, 'utf8'));
  const diags = (report.diagnostics || []).map((d) => {
    const bodyBits = [d.subj, (d.crashInfo?.stackTraces || []).join('\n'), (d.errs || []).join('\n')].filter(Boolean).join('\n');
    return { ...d, enriched: enrich(bodyBits) };
  });

  const actionable = diags
    .filter((d) => d.enriched.logIdShort || d.type === 'diagnostic' || d.enriched.signals.length)
    .sort((a, b) => String(b.date).localeCompare(String(a.date)));

  const rows = renderTreatTableRows(actionable, 20);
  const date = new Date().toISOString().slice(0, 10);

  const lines = [
    `# Gmail diagnostics treat — ${date}`,
    '',
    'Silent only. No forum posts. Auto-generated by `render-diag-treat.js`.',
    '',
    `Run: ${report.run?.mode || '?'} | emails: **${report.count || 0}** | access: ${report.access?.gmail?.ok ? 'OK' : report.access?.gmail?.code || 'blocked'}`,
    '',
    '| When UTC | Log ID | Couple / note | App | Signals |',
    '|----------|--------|---------------|-----|---------|',
  ];

  for (const r of rows) {
    lines.push(`| ${r.when || '—'} | \`${r.logId}\` | ${String(r.couple).replace(/\|/g, '\\|')} | ${r.app} | ${r.signals} |`);
  }

  if (!rows.length) {
    lines.push('| — | — | No structured diags in last run | — | — |');
  }

  lines.push('', '## Structured summaries', '');
  for (const d of actionable.slice(0, 12)) {
    const en = d.enriched;
    lines.push(`### ${en.logIdShort || d.type} — ${(d.subj || '').slice(0, 60)}`);
    lines.push('');
    lines.push(`- **Summary:** ${en.summary || 'n/a'}`);
    if (en.userMessage) lines.push(`- **User message:** ${en.userMessage}`);
    if (en.couples.length) {
      lines.push(`- **Couples:** ${en.couples.map((c) => `\`${c.mfr}+${c.pid}\``).join(', ')}`);
    }
    if (en.drivers.length) lines.push(`- **Drivers in log:** ${en.drivers.join(', ')}`);
    if (en.signals.length) {
      lines.push('- **Signals:**');
      for (const s of en.signals) lines.push(`  - \`${s.id}\` (${s.severity}) → ${s.fix}`);
    }
    if (en.highlights.length) {
      lines.push('- **Log highlights:**');
      for (const h of en.highlights.slice(0, 4)) lines.push(`  - ${h}`);
    }
    lines.push('');
  }

  lines.push('## Privacy (P2206)', '');
  lines.push('- Never commit raw `diag-*-excerpt.txt` or `gmail-ci-dump.json`.');
  lines.push('- Redact with `node .github/scripts/privacy-redactor.js` before git add.', '');

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const outFile = path.join(OUT_DIR, 'TREAT.md');
  fs.writeFileSync(outFile, `${lines.join('\n')}\n`);
  console.log('[render-diag-treat] wrote', outFile, '| rows:', rows.length);
}

main();
