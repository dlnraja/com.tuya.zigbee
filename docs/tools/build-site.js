function rel(fromPage, target) {
  const depth = fromPage.split('/').length - 1;
  return '../'.repeat(depth) + target;
}

function layout(page, title, body, opts = {}) {
  const nav = NAV.map(([href, label]) => '<a href="' + rel(page, href) + '"' + (href === page || (href === 'kb/index.html' && page.startsWith('kb/')) ? ' class="on"' : '') + '>' + label + '</a>').join('');
  return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' +
    '<title>' + esc(title) + ' · Universal Tuya docs</title><link rel="stylesheet" href="' + rel(page, 'style.css') + '"></head><body>' +
    '<header><a class="brand" href="' + rel(page, 'index.html') + '">Universal Tuya docs</a>' + nav + '</header><main>' + body + '</main>' +
    '<footer>Generated by <a href="' + D.REPO_URL + '/tree/master/docs/tools">docs/tools</a> from the repository data' + (opts.generatedFrom ? ' (' + esc(opts.generatedFrom) + ')' : '') +
    '. Report problems through <a href="' + D.ISSUES_URL + '">GitHub issues</a>. Device finder: <a href="' + rel(page, '../index.html') + '">home</a>.</footer></body></html>\n';
}

/** Map of md source path (repo-relative) -> site page, for link rewriting. */
function makeRewriter(page, srcRel, pageMap, branch) {
  return url => {
    if (/^(https?:|mailto:|#|data:)/i.test(url)) return url;
    const [p, hash] = url.split('#');
    if (!p) return url;
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(srcRel), p)).replace(/^\.\//, '');
    if (pageMap[resolved]) return rel(page, pageMap[resolved]) + (hash ? '#' + hash : '');
    if (resolved.startsWith('..')) return D.REPO_URL;
    return D.REPO_URL + '/blob/' + branch + '/' + resolved + (hash ? '#' + hash : '');
  };
}

function mdPage(page, srcRel, md, pageMap, branch, extra) {
  const r = render(D.scrub(md), { rewriteLink: makeRewriter(page, srcRel, pageMap, branch) });
  const t = /^#\s+(.+)$/m.exec(md);
  return layout(page, t ? t[1].replace(/[`*]/g, '') : page, r.html + (extra || ''), { generatedFrom: srcRel });
}

function readIf(p) { try { return fs.readFileSync(p, 'utf8'); } catch (_) { return null; } }

function listKb(root) {
  const out = [];
  const kbDir = path.join(root, 'docs', 'knowledge', 'KB');
  const nDir = path.join(root, 'docs', 'knowledge');
  for (const [dir, prefix, group] of [[kbDir, 'docs/knowledge/KB/', 'Knowledge base (curated)'], [nDir, 'docs/knowledge/', 'Engineering notes']]) {
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (!f.endsWith('.md') || f === 'KB_SOURCES.md' || /^DAILY_RESUME/.test(f)) continue;
      const slugName = (prefix.endsWith('KB/') ? 'kb-' : '') + f.replace(/\.md$/, '');
      out.push({ src: prefix + f, page: 'kb/' + slugName + '.html', group, file: path.join(dir, f) });
    }
  }
  return out;
}

