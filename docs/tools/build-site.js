function build(opts = {}) {
  const root = opts.root || ROOT;
  const out = opts.out || path.join(root, '.github', 'pages-build', 'docs');
  const apps = opts.apps && opts.apps.length ? opts.apps : [{ file: path.join(root, 'app.json') }];
  const branches = [];
  for (const a of apps) {
    const json = typeof a.json === 'object' && a.json ? a.json : JSON.parse(fs.readFileSync(a.file, 'utf8'));
    const branch = a.branch || D.branchFromAppId(json.id);
    const meta = D.BRANCHES[branch] || { branch, appId: json.id, title: D.pickName(json.name), role: '' };
    const devices = collectDevices(json, branch);
    branches.push(Object.assign({}, meta, { appId: json.id || meta.appId, title: D.pickName(json.name) || meta.title, version: json.version || '', devices, stats: D.stats(devices) }));
  }
  const homeBranch = branches[0].branch;
  fs.mkdirSync(path.join(out, 'kb'), { recursive: true });
  const written = [];
  const write = (p, s) => { fs.writeFileSync(path.join(out, p), s); written.push(p); };

  const kb = listKb(root);
  const pageMap = {
    'docs/site-src/faq.md': 'faq.html', 'docs/site-src/request-device.md': 'request-device.html',
    'docs/site-src/architecture.md': 'architecture.html', 'docs/site-src/contributing.md': 'contributing.html',
    'CREDITS.md': 'credits.html', 'docs/knowledge/KB_SOURCES.md': 'sources.html', 'docs/knowledge/KB/KB_SOURCES.md': 'sources.html', 'docs/KB_SOURCES.md': 'sources.html',
  };
  // site-src pages link to each other with .html names already; map their own names too
  for (const k of kb) pageMap[k.src] = k.page;

  write('style.css', CSS);
  write('index.html', layout('index.html', 'Home', homePage(branches), { generatedFrom: branches.map(b => b.branch + '/app.json').join(', ') }));
  for (const b of branches) write('devices-' + b.branch + '.json', JSON.stringify(b.devices));
  write('devices.html', layout('devices.html', 'Supported devices', devicesPage(branches), { generatedFrom: 'app.json' }));
  for (const name of ['faq', 'request-device', 'architecture', 'contributing']) {
    const src = 'docs/site-src/' + name + '.md';
    write(name + '.html', mdPage(name + '.html', src, fs.readFileSync(path.join(root, src), 'utf8'), pageMap, homeBranch));
  }
  const cl = readIf(path.join(root, '.homeychangelog.json'));
  write('changelog.html', layout('changelog.html', 'Changelog', changelogPage(cl ? JSON.parse(cl) : {}), { generatedFrom: '.homeychangelog.json' }));

  const credits = readIf(path.join(root, 'CREDITS.md')) || '# Credits\n\nSee the repository.';
  write('credits.html', mdPage('credits.html', 'CREDITS.md', credits, pageMap, homeBranch, '<p>Also see <a href="sources.html">sources</a>.</p>'));
  const srcCandidates = ['docs/knowledge/KB_SOURCES.md', 'docs/knowledge/KB/KB_SOURCES.md', 'docs/KB_SOURCES.md'];
  const srcFile = srcCandidates.find(f => fs.existsSync(path.join(root, f)));
  const sourcesMd = srcFile ? fs.readFileSync(path.join(root, srcFile), 'utf8') : DEFAULT_SOURCES;
  write('sources.html', mdPage('sources.html', srcFile || 'docs/site-src/sources.md', sourcesMd, pageMap, homeBranch, '<p>People and projects are credited on the <a href="credits.html">credits</a> page.</p>'));

  const groups = {};
  for (const k of kb) {
    write(k.page, mdPage(k.page, k.src, fs.readFileSync(k.file, 'utf8'), pageMap, homeBranch, '<p><a href="index.html">← Knowledge base index</a> · <a href="' + D.REPO_URL + '/blob/' + homeBranch + '/' + k.src + '">source</a></p>'));
    const title = (/^#\s+(.+)$/m.exec(fs.readFileSync(k.file, 'utf8')) || [, k.src])[1];
    (groups[k.group] = groups[k.group] || []).push('<li><a href="' + path.posix.basename(k.page) + '">' + esc(D.scrub(title.replace(/[`*]/g, ''))) + '</a> <span class="muted">' + esc(k.src) + '</span></li>');
  }
  write('kb/index.html', layout('kb/index.html', 'Knowledge base', '<h1>Knowledge base</h1><p>Our notes, written in our own words, on devices, protocols, Homey SDK pitfalls and past fixes. Each page links to its source file and credits the references it used. Sources: <a href="../sources.html">sources</a>.</p>' +
    Object.entries(groups).map(([g, items]) => '<h2>' + esc(g) + '</h2><ul>' + items.join('') + '</ul>').join('') + (kb.length ? '' : '<p>No pages yet.</p>'), { generatedFrom: 'docs/knowledge' }));
  return { out, pages: written, branches: branches.map(b => ({ branch: b.branch, version: b.version, stats: b.stats })) };
}

