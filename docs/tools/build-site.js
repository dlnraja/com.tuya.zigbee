function parseArgs(argv) {
  const o = { apps: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') o.out = path.resolve(argv[++i]);
    else if (argv[i] === '--app') { const [branch, file] = argv[++i].split('='); o.apps.push({ branch, file: path.resolve(file) }); }
  }
  return o;
}

