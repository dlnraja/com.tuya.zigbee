#!/usr/bin/env node
'use strict';
/**
 * Generates the root README.md of the current branch from app.json (SSOT),
 * .homeychangelog.json and the drivers folder. Branch-aware (master, stable-v5,
 * bastien-home are detected from the app id). Counts are never hand-typed.
 *
 * Usage: node docs/tools/build-readme.js [--root DIR] [--stdout]
 */
const fs = require('fs');
const path = require('path');
const D = require('./data');

function topRows(devices, n) {
  return devices.slice().sort((a, b) => b.mfrs.length - a.mfrs.length || a.id.localeCompare(b.id)).slice(0, n)
    .map((d, i) => '| ' + (i + 1) + ' | `' + d.id + '` | ' + d.class + ' | ' + D.fmt(d.mfrs.length) + ' | ' + d.pids.slice(0, 4).map(p => '`' + p + '`').join(', ') + (d.pids.length > 4 ? ' …' : '') + ' |').join('\n');
}

function latest(cl, n) {
  const list = (cl && Array.isArray(cl.changelog)) ? cl.changelog : [];
  const cmp = require('./build-site').cmpVer;
  return list.slice().sort((a, b) => cmp(b.version, a.version)).slice(0, n)
    .map(e => '| ' + e.version + ' | ' + (e.date || '') + ' | ' + D.scrub(String(e.en || '').replace(/\|/g, '/').replace(/\s+/g, ' ')) + ' |').join('\n');
}

function render(app, opts = {}) {
  const branch = opts.branch || D.branchFromAppId(app.id);
  const meta = D.BRANCHES[branch];
  const devices = D.collectDevices(app, branch);
  const s = D.stats(devices);
  const links = D.installLinks(app.id);
  const title = D.pickName(app.name) || meta.title;
  const classes = Object.entries(s.classes).sort((a, b) => b[1] - a[1]).map(([c, n]) => '`' + c + '` ' + n).join(' · ');
  const others = Object.values(D.BRANCHES).filter(b => b.branch !== branch)
    .map(b => '- **' + b.title + '** (`' + b.branch + '`): ' + b.role + ' [Code](' + D.REPO_URL + '/tree/' + b.branch + ')').join('\n');
  const P = D.PAGES_URL;
  return `# ${title} for Homey

<!-- AUTO-GENERATED by docs/tools/build-readme.js from app.json — do not edit by hand. Edit the generator or docs/site-src/. -->

[![Version](https://img.shields.io/badge/version-${encodeURIComponent(app.version)}-blue)](${links.live})
[![Drivers](https://img.shields.io/badge/drivers-${s.drivers}-brightgreen)](${P}devices.html)
[![Docs](https://img.shields.io/badge/docs-GitHub%20Pages-informational)](${P})
[![Issues](https://img.shields.io/badge/report-GitHub%20issues-red)](${D.ISSUES_URL})

Local control of Tuya and white-label devices on Homey Pro, without the Tuya cloud for Zigbee.
This branch is \`${branch}\`: ${meta.role}

**Full documentation: ${P}** (searchable device list, FAQ, request guide, architecture, knowledge base).

## Install

| Channel | Link | What it is |
|---|---|---|
| Live | [${links.live}](${links.live}) | Checked versions |
| Test | [${links.test}](${links.test}) | Every new version first; fixes arrive here days earlier |

Use only one of the three apps for a given device. Versions go to **Test** first, then **Live** once they are checked.
Release notes: [changelog](${P}changelog.html) · [GitHub releases](${D.REPO_URL}/releases).

## Supported devices

Generated from \`app.json\` v${app.version}:

| Metric | Value |
|---|---|
| Drivers | ${D.fmt(s.drivers)} (${D.fmt(s.zigbee)} Zigbee, ${D.fmt(s.wifi)} Wi-Fi${s.other ? ', ' + D.fmt(s.other) + ' other' : ''}) |
| Manufacturer names (case-insensitive) | ${D.fmt(s.manufacturers)} |
| Model / product ids | ${D.fmt(s.productIds)} |
| Capabilities used | ${D.fmt(s.capabilities)} |

Search your device by manufacturer name or model: **[supported devices](${P}devices.html)**.

<details><summary>Top 15 drivers by manufacturer names</summary>

| # | Driver | Class | Manufacturer names | Models |
|---|---|---|---|---|
${topRows(devices, 15)}

</details>

<details><summary>Drivers by class</summary>

${classes}

</details>

## Report a problem or request a device

**GitHub issues are the way to report:** [open an issue](${D.NEW_ISSUE_URL}). Please include:

1. the **manufacturer name** (\`_TZE200_…\`, \`_TZ3000_…\`) and the **model** (\`TS0601\`, \`TS011F\`…) from Homey Developer Tools → Zigbee;
2. the **Zigbee interview** (Developer Tools → the device → Interview), waking battery devices with their button;
3. a **diagnostic report** code from this app (Apps → this app → Send diagnostic report);
4. what the device is and what goes wrong.

Do not post local keys, tokens or other personal data. Details: [device request guide](${P}request-device.html).

## Troubleshooting

| Problem | First thing to try |
|---|---|
| Pairs as unknown / generic / wrong class | Check the [device list](${P}devices.html); update (Test channel), remove and re-pair |
| Button does nothing | Use the device's own trigger card; check scene vs dimmer mode ([FAQ](${P}faq.html#scene-mode-vs-dimmer-mode)) |
| Clock or settings not applied on a battery device | Wake it with its button; writes wait for the next wake-up |
| Battery empty or stuck | Wait for the first report; some devices only send "battery low" |
| Wi-Fi device offline / one socket only | See the Wi-Fi section of the [FAQ](${P}faq.html#wi-fi-local-devices) |
| Flow card unknown | Re-select the card in the Flow and save |

All answers: **[FAQ](${P}faq.html)**.

## The three apps

${others}

## Documentation map

| Where | What |
|---|---|
| [Docs site](${P}) | Home, devices, FAQ, request guide, changelog, architecture, knowledge base, credits, sources, contributing |
| [docs/](docs/README.md) | Repository docs; [docs/site-src/](docs/site-src/) holds the hand-written pages, [docs/tools/](docs/tools/) the generators |
| [drivers/](drivers/README.md) | One folder per driver; \`driver.compose.json\` is the source of truth |
| [lib/](lib/README.md) | Shared runtime modules |
| [scripts/](scripts/README.md) | Maintenance and CI scripts (not shipped to Homey) |
| [CONTRIBUTING.md](CONTRIBUTING.md) | How to contribute ([web version](${P}contributing.html)) |
| [CREDITS.md](CREDITS.md) | People and projects we learned from ([web version](${P}credits.html)) |

## Latest changes

| Version | Date | Changes |
|---|---|---|
${latest(opts.changelog, 8)}

## Credits

This app builds on the Homey SDK and on public knowledge from Zigbee2MQTT, ZHA, deCONZ, Blakadder,
tuya-local, tinytuya, Johan Bendz's original Tuya Zigbee app and many community testers.
Everything is rewritten in our own words and code; see [CREDITS.md](CREDITS.md) and [sources](${P}sources.html).

## License

See [LICENSE](LICENSE). Community discussion: [Homey forum topic](${D.FORUM_URL}); bug reports: [GitHub issues](${D.ISSUES_URL}).
`;
}

function main(argv = process.argv.slice(2)) {
  const root = argv.includes('--root') ? path.resolve(argv[argv.indexOf('--root') + 1]) : path.join(__dirname, '..', '..');
  const app = JSON.parse(fs.readFileSync(path.join(root, 'app.json'), 'utf8'));
  let changelog = {};
  try { changelog = JSON.parse(fs.readFileSync(path.join(root, '.homeychangelog.json'), 'utf8')); } catch (_) { /* optional */ }
  const md = render(app, { changelog });
  if (argv.includes('--stdout')) process.stdout.write(md);
  else { fs.writeFileSync(path.join(root, 'README.md'), md); console.log('[readme] README.md regenerated for ' + D.branchFromAppId(app.id) + ' v' + app.version); }
  return md;
}

if (require.main === module) main();
module.exports = { render, main, topRows, latest };
