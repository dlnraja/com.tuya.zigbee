'use strict';
// P3069 (t585u): ratchet — no new workflow without an "about" header, no new script pasting
// third-party titles/bodies into reports, no new long quoted excerpt in docs, helper reports keep their shape.
const test = require('node:test');
const assert = require('node:assert');
const path = require('path');
const fs = require('fs');
const G = require(path.join(__dirname, '..', '..', 'scripts', 'ci', 'report-structure-ratchet.js'));
const base = JSON.parse(fs.readFileSync(path.join(__dirname, '..', '..', '.github', 'report-ratchet-baseline.json'), 'utf8'));

test('repository is at or below the baseline', () => {
  const errs = G.compare(G.collect(), base);
  assert.deepStrictEqual(errs, []);
});

test('regressions are caught', () => {
  const cur = { workflowsWithoutAbout: ['new.yml'], quotingScripts: [{ file: 'scripts/x.js', lines: 1 }], docExcerpts: { 'docs/knowledge/X.md': 2 }, brokenReports: [{ file: 'r.md', problems: ['missing thanks/credits line'] }] };
  const errs = G.compare(cur, { workflowsWithoutAbout: [], quotingScripts: [], docExcerpts: { 'docs/knowledge/X.md': 1 } });
  assert.strictEqual(errs.length, 4, errs.join('\n'));
});

test('quote detector: third-party fields yes, our own helpers no', () => {
  assert.ok(G.QUOTE_RE.test('L.push(`- [#${it.number}](${it.html_url}) ${it.title}`)'));
  assert.ok(G.QUOTE_RE.test('const t = `${p.cooked}`;'));
  assert.ok(!G.QUOTE_RE.test('L.push(`- ${sourceRef(x)}`)'));
  assert.ok(!G.QUOTE_RE.test('const t = `${report.title}`;'));
});

test('baseline may only shrink (no file listed that is now clean is required to stay)', () => {
  const cur = G.collect();
  assert.ok(cur.workflowsWithoutAbout.length <= base.workflowsWithoutAbout.length);
  assert.ok(cur.quotingScripts.length <= base.quotingScripts.length);
});

// P3069 step 3: refined detector — false positives gone, real quotes still caught.
const RW = require(path.join(__dirname, '..', '..', 'scripts', 'lib', 'report-writer.js'));
test('detector skips our own text: code spans, JSON/locale lines, packed sources, own-bot comments, callouts', () => {
  const own = [
    'Added `"AOYAN  "` (two spaces) next to the existing `"AOYAN"`, which changes nothing for units that send the plain name at all.',
    'DP8 "motor_speed" comes from a generic note and means something else on other covers, so exposing it could reverse motors. "My" is a setting.',
    '    "fr": "Appuyez et maintenez le bouton d\'appairage pendant 5 secondes jusqu\'à ce que la LED clignote.",',
    '<file path="app.json">', '"x": "one two three four five six seven eight nine ten eleven twelve thirteen"', '</file>',
    '> **dlnraja:** <!-- tuya-issue-manager -->', '> Thanks for the update, we have a significant number of new entries to review and I appreciate the breakdown.', '',
    '> **Superseded by** the roadmap file which is now the place where the day to day compass lives for everyone.',
    '> Generated by `tools/x.js`. Not Homey runtime — docs are excluded from the app bundle and never shipped to users.',
  ].join('\n');
  assert.deepStrictEqual(RW.findQuotedExcerpts(own), []);
});
test('detector still catches a pasted third-party comment and a long quote', () => {
  const md = [
    '> **someone:** I am sorry to say that the issue is not resolved for my energy plug after the update yesterday.',
    '',
    '- "When you upload your app, the files are stored separately and only fetched when the device update really starts." says the doc.',
  ].join('\n');
  const h = RW.findQuotedExcerpts(md);
  assert.deepStrictEqual(h.map((x) => x.kind), ['blockquote', 'quote']);
});
test('widened script scan: "+" concatenation into output counts, id extraction does not', () => {
  assert.ok(G.QUOTE_RE.test("md.push('- #' + i.number + ' ' + issue.title);"));
  assert.ok(G.ANALYSIS_RE.test("const text = (issue.title || '') + ' ' + (issue.body || '');"));
  assert.ok(!G.QUOTE_RE.test('if (issue.title === "x") return;'));
});
test('docs/knowledge and CREDITS.md carry no long quoted excerpt any more', () => {
  const cur = G.collect();
  const left = Object.keys(cur.docExcerpts).filter((f) => f.startsWith('docs/knowledge/') || /CREDITS\.md$/.test(f));
  assert.deepStrictEqual(left, []);
});

// P3069 step 4: digests and logs link to the source with a topic instead of repeating its title.
test('a file that declares itself our own text near the top is not scanned; lower down it does not count', () => {
  const quote = '> I am sorry to say that the issue is not resolved for my energy plug after the update yesterday.';
  assert.deepStrictEqual(RW.findQuotedExcerpts(['# Plan', '<!-- own-text-file: our own rules -->', '', quote].join('\n')), []);
  const late = ['# x', '', '', '', '', '', '<!-- own-text-file: late -->', quote].join('\n');
  assert.strictEqual(RW.findQuotedExcerpts(late).length, 1);
  assert.strictEqual(RW.findQuotedExcerpts(['<!-- own-text-file: -->', quote].join('\n')).length, 1, 'a reason is required');
});
test('weekly loop, forum searches, comment collector and issue manager no longer echo third-party titles', () => {
  const fs = require('fs');
  const ROOT = path.join(__dirname, '..', '..');
  const flagged = G.scanScripts().map((x) => x.file);
  for (const f of ['tools/ci/weekly-sovereign-loop.js', 'tools/ci/search-forum-posts.js', 'tools/ci/search-forum-posts-v2.js',
    'tools/ci/collect-johan-comments-to-delete.js', '.github/scripts/github-issue-manager.js', '.github/scripts/nightly-processor.js']) {
    if (!fs.existsSync(path.join(ROOT, f))) continue;
    assert.ok(!flagged.includes(f), `${f} still quotes a title or body`);
  }
  const w = fs.readFileSync(path.join(ROOT, 'tools/ci/weekly-sovereign-loop.js'), 'utf8');
  assert.match(w, /linkRef\(\{ id: i\.number, url: i\.url, text: i\.title \}\)/);
  const gm = fs.readFileSync(path.join(ROOT, '.github/scripts/github-issue-manager.js'), 'utf8');
  assert.match(gm, /forumMsg='\*\*GitHub #'\+issue\.number\+'\*\* — '\+topicOf\(issue\.title\)/);
  assert.strictEqual((gm.match(/ok-extract-only: AI prompt input/g) || []).length, 2);
});
test('linkRef gives a link and topic words, never the title itself', () => {
  const title = 'My kitchen light _TZ3000_abcdefgh keeps turning off after a few hours';
  const s = RW.linkRef({ id: 12, url: 'https://x/12', text: title });
  assert.ok(s.startsWith('[#12](https://x/12)'));
  assert.ok(!s.includes('keeps turning off'));
});
