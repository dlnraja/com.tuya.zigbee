#!/usr/bin/env node
'use strict';
// P3103: weekly autonomy digest — one issue, edited in place. Inputs are GitHub's own data (runs, issues)
// and repo state files; everything is counts and links, no third-party text.
const fs = require('fs');
const { execFileSync } = require('child_process');
const gh = (a, input) => execFileSync('gh', a, { encoding: 'utf8', input, maxBuffer: 64e6 });

function summarize(runs, since) {
  const by = {};
  for (const r of runs) { if (new Date(r.createdAt) < since) continue; const k = r.workflowName; by[k] = by[k] || { ok: 0, red: 0 }; if (r.conclusion === 'success') by[k].ok++; else if (r.conclusion === 'failure') by[k].red++; }
  return Object.entries(by).sort((a, b) => b[1].red - a[1].red);
}
function body({ rows, crash, reverts, ledger, paused, week }) {
  const lines = [`Week ending ${week} (generated by autonomy-digest, P3103).`, '', '## Workflows with failures (7 days)', '', '| Workflow | green | red |', '|---|---|---|'];
  rows.filter(([, v]) => v.red).slice(0, 25).forEach(([k, v]) => lines.push(`| ${k.replace(/\|/g, '/')} | ${v.ok} | ${v.red} |`));
  if (!rows.some(([, v]) => v.red)) lines.push('| none | | |');
  lines.push('', '## Autonomy', '', `- Open crash-triage issues: ${crash}`, `- Auto-reverts this week: ${reverts}`, `- Ledger entries: ${ledger.total}, promoted: ${ledger.promoted}`, `- Kill switches on: ${paused.length ? paused.join(', ') : 'none'}`);
  return lines.join('\n');
}
module.exports = { summarize, body };

if (require.main === module) {
  const since = new Date(Date.now() - 7 * 864e5);
  const runs = JSON.parse(gh(['run', 'list', '-L', '1000', '--json', 'workflowName,conclusion,createdAt']));
  const crash = JSON.parse(gh(['issue', 'list', '--label', 'crash-triage', '--state', 'open', '-L', '200', '--json', 'number'])).length;
  const reverts = execFileSync('git', ['log', '--since=7.days', '--format=%s'], { encoding: 'utf8' }).split('\n').filter((s) => s.includes('[auto:revert-on-red]')).length;
  let l = {}; try { l = JSON.parse(fs.readFileSync('config/autonomy-learned.json', 'utf8')); } catch { /* none */ }
  const entries = Object.values(l.entries || {});
  const paused = fs.readdirSync('config').filter((f) => f.startsWith('autonomy-paused'));
  const b = body({ rows: summarize(runs, since), crash, reverts, ledger: { total: entries.length, promoted: entries.filter((e) => e && e.auto).length }, paused, week: new Date().toISOString().slice(0, 10) });
  const title = 'Autonomy weekly digest';
  const ex = JSON.parse(gh(['issue', 'list', '--state', 'open', '--search', `in:title "${title}"`, '-L', '5', '--json', 'number,title'])).find((i) => i.title === title);
  if (ex) gh(['issue', 'edit', String(ex.number), '--body-file', '-'], b); else gh(['issue', 'create', '--title', title, '--body-file', '-'], b);
  console.log(b);
}
