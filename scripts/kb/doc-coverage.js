#!/usr/bin/env node
'use strict';
/**
 * P3032: documentation coverage inventory (report mode, always exit 0 unless --strict).
 * Compares what exists in code (lib modules, gates/CI scripts, workflows, env flags, drivers,
 * KB files) with what the docs mention, and writes docs/knowledge/KB/DOC_COVERAGE.md.
 * Deterministic: sorted lists, no timestamps. Reads only this tree, so the output is per branch.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(process.argv.find((a) => a.startsWith('--root='))?.slice(7) || path.join(__dirname, '..', '..'));
const OUT_REL = 'docs/knowledge/KB/DOC_COVERAGE.md';

function walk(dir, filter, acc = []) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return acc; }
  for (const e of entries) {
    if (e.name === 'node_modules' || e.name.startsWith('.git') || e.name === 'build') {continue;}
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {walk(p, filter, acc);} else if (filter(p)) {acc.push(p);}
  }
  return acc;
}
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

function docCorpus() {
  const files = [
    ...walk(path.join(ROOT, 'docs'), (p) => p.endsWith('.md') && !p.endsWith('DOC_COVERAGE.md') && !p.endsWith('CODE_REFERENCE.md')),
    ...['README.md', 'CHANGELOG.md', 'CREDITS.md'].map((f) => path.join(ROOT, f)).filter((f) => fs.existsSync(f)),
  ];
  let text = '';
  for (const f of files) { try { text += `\n${  fs.readFileSync(f, 'utf8')}`; } catch (_) { /* skip */ } }
  return text;
}

function inventory() {
  const corpus = docCorpus();
  const mentioned = (name) => corpus.includes(name);
  const lib = walk(path.join(ROOT, 'lib'), (p) => p.endsWith('.js') && !p.includes(`${path.sep}data${path.sep}`)).map(rel);
  const gates = [
    ...walk(path.join(ROOT, 'scripts', 'gates'), (p) => /\.(c?js)$/.test(p)),
    ...walk(path.join(ROOT, 'scripts', 'ci'), (p) => /\.(c?js)$/.test(p)),
    ...walk(path.join(ROOT, 'tools', 'ci'), (p) => /\.(c?js)$/.test(p)),
  ].map(rel);
  const workflows = walk(path.join(ROOT, '.github', 'workflows'), (p) => /\.ya?ml$/.test(p)).map(rel);
  const drivers = (() => { try { return fs.readdirSync(path.join(ROOT, 'drivers')).filter((d) => fs.existsSync(path.join(ROOT, 'drivers', d, 'driver.compose.json'))); } catch (_) { return []; } })();
  const envSet = new Set();
  for (const f of [...walk(path.join(ROOT, 'scripts'), (p) => /\.(c?js)$/.test(p)), ...walk(path.join(ROOT, 'tools'), (p) => /\.(c?js)$/.test(p)), ...walk(path.join(ROOT, 'lib'), (p) => p.endsWith('.js'))]) {
    let s = '';
    try { s = fs.readFileSync(f, 'utf8'); } catch (_) { continue; }
    for (const m of s.matchAll(/process\.env\.([A-Z][A-Z0-9_]{2,})/g)) {envSet.add(m[1]);}
  }
  const env = [...envSet].sort();
  const kbDir = path.join(ROOT, 'docs', 'knowledge', 'KB');
  const indexText = (() => { try { return fs.readFileSync(path.join(kbDir, 'INDEX.md'), 'utf8'); } catch (_) { return ''; } })();
  const kbFiles = (() => { try { return fs.readdirSync(kbDir).filter((f) => f.endsWith('.md') && f !== 'INDEX.md').sort(); } catch (_) { return []; } })();
  const base = (p) => path.basename(p).replace(/\.(c?js|ya?ml)$/, '');
  const pick = (list, key) => {
    const missing = list.filter((x) => !mentioned(key(x))).sort();
    return { total: list.length, documented: list.length - missing.length, missing };
  };
  return {
    lib: pick(lib, base),
    gates: pick(gates, base),
    workflows: pick(workflows, (w) => path.basename(w)),
    env: pick(env, (e) => e),
    drivers: pick(drivers, (d) => d),
    kbIndex: { total: kbFiles.length, documented: kbFiles.filter((f) => indexText.includes(f)).length, missing: kbFiles.filter((f) => !indexText.includes(f)) },
  };
}

function render(inv) {
  const rows = [
    ['lib modules (`lib/**/*.js`, data excluded)', inv.lib],
    ['gates and CI scripts (`scripts/gates`, `scripts/ci`, `tools/ci`)', inv.gates],
    ['workflows (`.github/workflows`)', inv.workflows],
    ['env flags (`process.env.*` in scripts/tools/lib)', inv.env],
    ['drivers (`drivers/*/driver.compose.json`)', inv.drivers],
    ['KB files listed in `KB/INDEX.md`', inv.kbIndex],
  ];
  let md = '# Documentation coverage (generated)\n\n';
  md += 'Generated by `scripts/kb/doc-coverage.js` (P3032) from this branch\'s own tree. Report mode: CI lists what is not documented and never fails. "Documented" means the name appears in at least one hand-written file under `docs/`, `README.md`, `CHANGELOG.md` or `CREDITS.md`; the generated [CODE_REFERENCE](CODE_REFERENCE.md) (header line of every file) does not count. See also [INDEX](INDEX.md), [Method coverage](METHOD_COVERAGE.md), [DP × endpoint coverage](DP_ENDPOINT_COVERAGE.md).\n\n';
  md += '| Area | Total | Documented | Missing |\n|---|---:|---:|---:|\n';
  for (const [label, r] of rows) {md += `| ${label} | ${r.total} | ${r.documented} | ${r.missing.length} |\n`;}
  for (const [label, r] of rows) {
    md += `\n## Not documented yet: ${label}\n\n`;
    md += r.missing.length ? `${r.missing.map((m) => `- \`${m}\``).join('\n')  }\n` : '_None._\n';
  }
  return md;
}

function main() {
  const inv = inventory();
  const md = render(inv);
  const out = path.join(ROOT, OUT_REL);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    console.log(cur === md ? 'doc-coverage: up to date' : 'doc-coverage: stale (report only)');
  } else if (!process.argv.includes('--stdout')) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, md);
  } else {process.stdout.write(md);}
  const missing = Object.values(inv).reduce((n, r) => n + r.missing.length, 0);
  console.log(`doc-coverage: ${missing} undocumented item(s) (report mode)`);
  if (process.argv.includes('--strict') && missing > 0) {process.exitCode = 1;}
}

if (require.main === module) {main();}
module.exports = { inventory, render };
