#!/usr/bin/env node
'use strict';

/**
 * P3017: write docs/knowledge/KB/METHOD_COVERAGE.md, the family × method matrix computed from
 * lib/zigbee/MethodCoverage.coverageMatrix(). Each cell is checked against the real module/export.
 * Deterministic: re-runs give byte-identical output unless code changes.
 */
const fs = require('fs');
const path = require('path');
const COV = require('../../lib/zigbee/MethodCoverage');

const OUT = path.join(__dirname, '..', '..', 'docs', 'knowledge', 'KB', 'METHOD_COVERAGE.md');
const SYM = { yes: '✅', 'n/a': '—', 'dp-only': 'DP', missing: '❌' };

function render() {
  const m = COV.coverageMatrix();
  const ids = COV.METHODS.map((x) => x.id);
  const short = ids.map((_, i) => `M${i + 1}`);
  const lines = [
    '# Method coverage (P3017): family × method',
    '',
    'Generated by `scripts/kb/method-coverage.js` from `lib/zigbee/MethodCoverage.js`. ✅ = implemented and applied, — = not applicable (reason below), ❌ = missing.',
    '',
    '| # | method | group | implementation |',
    '|---|---|---|---|',
    ...COV.METHODS.map((x, i) => `| M${i + 1} | ${x.id} | ${x.group} | \`lib/zigbee/${x.impl[0].replace('./', '')}.js\` → \`${x.impl[1]}\` |`),
    '',
    `| family | ${short.join(' | ')} |`,
    `|---|${short.map(() => '---').join('|')}|`,
    ...Object.entries(m).map(([f, row]) => `| ${f} | ${ids.map((id) => SYM[row[id]] || row[id]).join(' | ')} |`),
    '',
    '## Why some cells are "—"',
    '',
    '- **Private-cluster read (M3)**: only where Z2M/ZHA define a private attribute for that capability (E001 power-on, genOnOff 0x5000 backlight, closures 0xF000 moving state, E002 alarm thresholds).',
    '- **Derived (M7)**: only computable capabilities (power = V × I, current = P / V, alarm_battery ≤ 20 %, onoff ⇐ power > 0.5 W). Never written back to the device.',
    '- **Write methods (M8–M10)**: sensor-only families (IAS, buttons, soil) have nothing to write. Manufacturer-specific writes only exist where a private cluster exists.',
    '- Write failover never races EF00 DPs against ZCL on multi-gang ZCL switches (cross-link lesson, P92.122/CapabilityCommandRouter).',
    '',
    '## Chain order and behaviour',
    '',
    '`zcl-native → zcl-raw-numeric → tuya-dp → tuya-private → alt-endpoint → poll → magic-query → derived` (lib/zigbee/MethodChain.js).',
    'Unsupported (0x81/0x84/0x86/0xC3) demotes at once; timeout demotes after 2 in a row; other errors fail over without demotion.',
    'A demoted method is re-probed after 15 min, 1 h, 4 h, 12 h, then every 24 h. The winner is remembered per device (store `method_chain_state`, at most 60 domains).',
    'Capabilities are never added or removed by the chain. Entry points: `device.refreshCapabilityChain(cap)`, `readSensorWithFallbacks(..., { failover: true })` (used by the reporting → polling fallback), `writeCapabilityWithFallbacks`.',
    '',
  ];
  return lines.join('\n');
}

if (require.main === module) { fs.writeFileSync(OUT, render()); console.log(`wrote ${path.relative(process.cwd(), OUT)}`); }
module.exports = { render };
