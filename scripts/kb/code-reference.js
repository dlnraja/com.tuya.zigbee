#!/usr/bin/env node
'use strict';
/**
 * P3032: code reference generated from this branch's own sources.
 * One line per lib module, gate/CI script and workflow, taken from the file's own header
 * comment (or workflow `name:`), plus every env flag with the files that read it.
 * Writes docs/knowledge/KB/CODE_REFERENCE.md. Deterministic (sorted, no timestamps).
 * Items without a header comment are listed as "no header" so they can be described by hand.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(process.argv.find((a) => a.startsWith('--root='))?.slice(7) || path.join(__dirname, '..', '..'));
const OUT_REL = 'docs/knowledge/KB/CODE_REFERENCE.md';

function walk(dir, filter, acc = []) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return acc; }
  for (const e of entries) {
    if (e.name === 'node_modules' || e.name.startsWith('.git') || e.name === 'build') {continue;}
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {walk(p, filter, acc);} else if (filter(p)) {acc.push(p);}
  }
  return acc;
}
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
const clean = (s) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim().slice(0, 220);

function headerOf(src) {
  const s = src.replace(/^#!.*\n/, '').replace(/^\s*['"]use strict['"];?\s*/, '');
  const block = s.match(/^\s*\/\*\*?([\s\S]*?)\*\//);
  let text = '';
  if (block) {
    text = block[1].split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim())
      .filter((l) => l && !l.startsWith('@') && !/^eslint|^global /.test(l)).join(' ');
  } else {
    const lines = [];
    for (const l of s.split('\n')) { const m = l.match(/^\s*\/\/\s?(.*)$/); if (m) {lines.push(m[1]);} else if (l.trim()) {break;} }
    text = lines.filter((l) => !/^eslint/.test(l)).join(' ');
  }
  text = clean(text);
  const dot = text.search(/\.\s/);
  return dot > 30 ? text.slice(0, dot + 1) : text;
}

function build() {
  const read = (f) => { try { return fs.readFileSync(f, 'utf8'); } catch (_) { return ''; } };
  const section = (title, files, describe) => {
    let md = `\n## ${title} (${files.length})\n\n| File | Purpose (from its header) |\n|---|---|\n`;
    for (const f of files) {md += `| \`${rel(f)}\` | ${describe(f) || '_no header_'} |\n`;}
    return md;
  };
  const js = (p) => /\.(c?js)$/.test(p);
  const lib = walk(path.join(ROOT, 'lib'), (p) => p.endsWith('.js') && !p.includes(`${path.sep}data${path.sep}`)).sort();
  const gates = [path.join(ROOT, 'scripts', 'gates'), path.join(ROOT, 'scripts', 'ci'), path.join(ROOT, 'tools', 'ci')]
    .flatMap((d) => walk(d, js)).sort();
  const wfs = walk(path.join(ROOT, '.github', 'workflows'), (p) => /\.ya?ml$/.test(p)).sort();
  const env = new Map();
  for (const f of [...lib, ...walk(path.join(ROOT, 'scripts'), js), ...walk(path.join(ROOT, 'tools'), js)]) {
    for (const m of read(f).matchAll(/process\.env\.([A-Z][A-Z0-9_]{2,})/g)) {
      if (!env.has(m[1])) {env.set(m[1], new Set());}
      env.get(m[1]).add(rel(f));
    }
  }
  let md = '# Code reference (generated)\n\n';
  md += 'Generated by `scripts/kb/code-reference.js` (P3032) from this branch\'s own files; each purpose line is the file\'s own header comment, so it is exactly as current as the code. Regenerate after adding a module, gate, workflow or env flag. Undocumented items: [DOC_COVERAGE](DOC_COVERAGE.md). Index: [INDEX](INDEX.md).\n';
  md += section('lib modules', lib, (f) => headerOf(read(f)));
  md += section('Gates and CI scripts', gates, (f) => headerOf(read(f)));
  md += section('Workflows', wfs, (f) => { const m = read(f).match(/^name:\s*(.+)$/m); return m ? clean(m[1].replace(/^['"]|['"]$/g, '')) : ''; });
  const keys = [...env.keys()].sort();
  md += `\n## Env flags (${keys.length})\n\n| Flag | Read by |\n|---|---|\n`;
  for (const k of keys) {
    const files = [...env.get(k)].sort();
    md += `| \`${k}\` | ${files.slice(0, 4).map((f) => `\`${f}\``).join(', ')}${files.length > 4 ? ` +${files.length - 4}` : ''} |\n`;
  }
  return md;
}

if (require.main === module) {
  const md = build();
  const out = path.join(ROOT, OUT_REL);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    console.log(cur === md ? 'code-reference: up to date' : 'code-reference: stale (report only)');
  } else { fs.writeFileSync(out, md); console.log(`code-reference: wrote ${OUT_REL}`); }
}
module.exports = { build, headerOf };
