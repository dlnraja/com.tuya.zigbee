#!/usr/bin/env node
'use strict';
// Spec 002: build data/native-matrix.json (SSOT) + docs/NATIVE_MATRIX.md.
// native = cluster class shipped by athombv/node-zigbee-clusters; capability mapping =
// athombv/homey-zigbeedriver lib/system/capabilities/<cap>/<cluster>.js. Census = counts of
// clusters seen in docs/data/interviews/*.json (input/output) and in driver endpoint manifests.
// Offline, deterministic (no timestamps), no copied text.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const { CLUSTER } = require('zigbee-clusters');

const NON_NATIVE_FIXED = { 0xEF00: 'Tuya DP (private)', 0xEF01: 'Tuya private', 0xE000: 'Tuya private (E000)', 0xE001: 'Tuya private (E001)', 0xE002: 'Tuya private (E002)' };
const hex = (n) => `0x${Number(n).toString(16).toUpperCase().padStart(4, '0')}`;

const clusters = {};
for (const c of Object.values(CLUSTER)) {
  clusters[hex(c.ID)] = { id: c.ID, name: c.NAME, native: true, source: 'zigbee-clusters', capabilities: [], interviews: 0, drivers: 0 };
}
const capDir = path.join(ROOT, 'node_modules', 'homey-zigbeedriver', 'lib', 'system', 'capabilities');
if (fs.existsSync(capDir)) {
  const byName = Object.fromEntries(Object.values(clusters).map((c) => [c.name, c]));
  for (const cap of fs.readdirSync(capDir).sort()) {
    for (const f of fs.readdirSync(path.join(capDir, cap))) {
      const c = byName[f.replace(/\.js$/, '')];
      if (c && !c.capabilities.includes(cap)) c.capabilities.push(cap);
    }
  }
}
const touch = (id) => {
  const k = hex(id);
  if (!clusters[k]) {
    const priv = NON_NATIVE_FIXED[id];
    clusters[k] = { id: Number(id), name: priv || (id >= 0xFC00 ? 'manufacturer-specific' : 'unknown'), native: false, source: priv ? 'tuya' : 'observed', capabilities: [], interviews: 0, drivers: 0 };
  }
  return clusters[k];
};
for (const id of Object.keys(NON_NATIVE_FIXED)) touch(Number(id));

const intDir = path.join(ROOT, 'docs', 'data', 'interviews');
let interviews = 0;
if (fs.existsSync(intDir)) {
  for (const f of fs.readdirSync(intDir).filter((x) => x.endsWith('.json')).sort()) {
    let j; try { j = JSON.parse(fs.readFileSync(path.join(intDir, f), 'utf8')); } catch { continue; }
    const asList = (v) => (Array.isArray(v) ? v : (v && typeof v === 'object' ? Object.values(v).flat() : []));
    const toId = (x) => (typeof x === 'string' && /^0x/i.test(x) ? parseInt(x, 16) : Number(x));
    const ids = new Set([...asList(j.inputClusters), ...asList(j.outputClusters)].map(toId).filter(Number.isFinite));
    if (!ids.size) continue;
    interviews++;
    for (const id of ids) touch(id).interviews++;
  }
}
const drvDir = path.join(ROOT, 'drivers');
for (const d of fs.readdirSync(drvDir).sort()) {
  const f = path.join(drvDir, d, 'driver.compose.json');
  if (!fs.existsSync(f)) continue;
  let j; try { j = JSON.parse(fs.readFileSync(f, 'utf8')); } catch { continue; }
  const ids = new Set();
  for (const ep of Object.values((j.zigbee && j.zigbee.endpoints) || {})) for (const c of (ep && ep.clusters) || []) if (Number.isFinite(Number(c))) ids.add(Number(c));
  for (const id of ids) touch(id).drivers++;
}
const sorted = Object.fromEntries(Object.entries(clusters).sort(([a], [b]) => a.localeCompare(b)));
const out = {
  note: 'Spec 002 SSOT. Generated by scripts/gen/native-matrix.js — do not edit by hand.',
  rules: { nativeFirst: true, nonNativeNeverMandatoryForPairing: true, nonNativeRange: '0xFC00-0xFFFF + 0xE000-0xE002 + 0xEF00/0xEF01' },
  sources: ['https://github.com/athombv/node-zigbee-clusters', 'https://github.com/athombv/node-homey-zigbeedriver', 'https://apps.developer.homey.app/wireless/zigbee'],
  interviewsScanned: interviews,
  clusters: sorted,
};
fs.writeFileSync(path.join(ROOT, 'data', 'native-matrix.json'), JSON.stringify(out, null, 1) + '\n');
const rows = Object.entries(sorted).map(([k, c]) => `| ${k} | ${c.name} | ${c.native ? 'yes' : '**no**'} | ${c.capabilities.join(', ') || '—'} | ${c.interviews} | ${c.drivers} |`);
const md = `# Native vs non-native Zigbee clusters\n\nGenerated from \`data/native-matrix.json\` (\`node scripts/gen/native-matrix.js\`). Native = class in athombv zigbee-clusters; capabilities = homey-zigbeedriver system mappings. Interviews scanned: ${interviews}.\n\nRules (constitution D1/D2): native first; non-native clusters are additive fallbacks and never mandatory for pairing. Gate: \`npm run validate:native-matrix\`.\n\n| Cluster | Name | Native | Homey system capabilities | Interviews | Drivers (endpoint manifest) |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'NATIVE_MATRIX.md'), md);
console.log(`native-matrix: ${Object.keys(sorted).length} clusters, ${interviews} interviews`);
