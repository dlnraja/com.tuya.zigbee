#!/usr/bin/env node
'use strict';
/**
 * Generates the shared rules block of every agent-instruction file from the single source
 * .specify/memory/constitution.md (W8: reuse our own tooling, one SSOT). Additive: only the
 * text between the markers is rewritten; the rest of each file is left untouched.
 *   node scripts/gen/agent-rules.js          -> write
 *   node scripts/gen/agent-rules.js --check  -> exit 1 if any file is stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, '.specify', 'memory', 'constitution.md');
const BEGIN = '<!-- CONSTITUTION:BEGIN (generated by scripts/gen/agent-rules.js — edit the constitution, not this block) -->';
const END = '<!-- CONSTITUTION:END -->';
const TARGETS = ['AGENTS.md', 'CORE_RULES.md', '.cursorrules', '.clinerules', '.windsurfrules',
  '.agents/rules/constitution.md', '.gemini/rules/constitution.md'];

const NO_AUTO_POST = [
  '',
  '## Agent safety (generated)',
  '- Never post, comment, reply or send on GitHub, the Homey forum, email or chat on your own: draft and ask the maintainer.',
  '- Never force-push or rewrite published history; never break the three app IDs.',
  '- Read `data/progress/ledger.json` before working and record after (W3).',
].join('\n');

function block() {
  const body = fs.readFileSync(SRC, 'utf8').trim();
  return `${BEGIN}\n${body}\n${NO_AUTO_POST}\n${END}`;
}

function apply(file, b, check) {
  const p = path.join(ROOT, file);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  let next;
  const i = cur.indexOf(BEGIN);
  const j = cur.indexOf(END);
  if (i >= 0 && j > i) {next = cur.slice(0, i) + b + cur.slice(j + END.length);}
  else {next = `${cur.replace(/\s*$/, '')}${cur ? '\n\n' : ''}${b}\n`;}
  if (next === cur) {return false;}
  if (!check) {fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, next);}
  return true;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const b = block();
  const stale = TARGETS.filter((t) => apply(t, b, check));
  console.log(`[agent-rules] ${check ? 'stale' : 'updated'}: ${stale.length ? stale.join(', ') : 'none'}`);
  if (check && stale.length) {process.exit(1);}
}

module.exports = { block, TARGETS, BEGIN, END };
